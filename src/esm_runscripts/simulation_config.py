"""
ConfigBuilder and SimulationConfig for building simulation configurations.

Extracts config-building logic from SimulationSetup.__init__ into a clean,
chainable Builder/Product pair. ConfigBuilder provides a fluent interface for
building configurations step-by-step, while SimulationConfig holds the final result.

Also provides RunStateBuilder and RunState, which wrap the per-invocation,
pplan-only steps (dates, calendar, folders, prev_date, parent_info) that
today run inside prepare.py's recipe. The legacy engine never touches this
code; it keeps calling prepare.run_job wholesale.
"""

import copy

from . import chunky_parts, conda_env, config_initialization, last_minute, prepare
# Imported directly from the submodule, not via `from . import batch_system`:
# esm_runscripts/__init__.py's `from .batch_system import *` shadows the
# package-level `batch_system` attribute with this same class once the real
# package has loaded, so `batch_system.batch_system.find_openmp(...)` breaks
# in production (confirmed by CI) even though it works when this module is
# loaded in isolation. `compute.py`/`prepcompute.py` already use this same
# direct-import form for the same reason.
from .batch_system import batch_system as BatchSystem


class SimulationConfig:
    """
    Immutable product of the configuration building process.

    Holds the final configuration dictionary generated by ConfigBuilder.
    The data property exposes the underlying dict by convention (not enforced),
    matching how esm_parser.ConfigSetup is used elsewhere in this codebase.
    """

    def __init__(self, data):
        """
        Initialize a SimulationConfig with the final configuration data.

        Parameters
        ----------
        data : dict
            The final configuration dictionary.
        """
        self._data = data

    @property
    def data(self):
        """Return the underlying configuration dictionary (read-only by convention)."""
        return self._data


class ConfigBuilder:
    """
    Mutable builder for simulation configurations.

    Provides a fluent interface with chainable .with_*() methods that wrap
    individual config initialization functions. Each method mutates self._data
    in place and returns self for chaining.

    Usage:
        builder = ConfigBuilder.from_runscript("path/to/runscript.yaml")
        config = (
            builder
            .with_interactive_info()
            .with_iterative_coupling()
            .with_execution_mode_default()
            .expand_from_esm_tools_configs()
            .with_runscript_defaults()
            .validate_account()
            .with_inspect_info()
            .remember_command_line()
            .build()
        )
    """

    def __init__(self, user_config, command_line_config=None):
        """
        Initialize a ConfigBuilder with user config and optional command line config.

        Parameters
        ----------
        user_config : dict
            The user configuration dictionary (from runscript or passed directly).
        command_line_config : dict, optional
            Command line configuration dictionary. Passed through as-is, including None.
        """
        self._data = user_config
        self._command_line_config = command_line_config

    @classmethod
    def from_runscript(cls, path, **overrides):
        """
        Create a ConfigBuilder from a runscript file.

        Reads the runscript and creates a builder with the parsed configuration.
        Command line overrides are merged in, with special handling for the 'task'
        parameter (mapped to 'jobtype').

        Parameters
        ----------
        path : str
            Absolute path to the runscript file.
        **overrides : dict
            Keyword arguments to override values in the configuration.
            Special case: 'task' is mapped to 'jobtype'.

        Returns
        -------
        ConfigBuilder
            A new builder instance with the loaded configuration.
        """
        # Build command_line_config with runscript path and overrides
        command_line_config = {"runscript_abspath": path}

        # Map 'task' override to 'jobtype' for consistency with CLI behavior
        for key, value in overrides.items():
            if key == "task":
                command_line_config["jobtype"] = value
            else:
                command_line_config[key] = value

        # Load user config from runscript
        user_config = config_initialization.get_user_config_from_command_line(
            command_line_config
        )

        return cls(user_config, command_line_config)

    @classmethod
    def from_user_config(cls, user_config):
        """
        Create a ConfigBuilder from a user configuration dictionary directly.

        This bypasses runscript loading entirely, useful when user_config is
        already in memory or constructed programmatically.

        Parameters
        ----------
        user_config : dict
            The user configuration dictionary.

        Returns
        -------
        ConfigBuilder
            A new builder instance with the provided configuration.
        """
        return cls(user_config, command_line_config=None)

    def with_interactive_info(self):
        """
        Initialize interactive session tracking.

        Sets 'isinteractive' and 'isresubmitted' flags based on command_line_config.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.init_interactive_info(
            self._data, self._command_line_config
        )
        return self

    def with_iterative_coupling(self):
        """
        Initialize iterative coupling (offline coupling) information.

        Completes configuration for offline coupling simulations if applicable.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.init_iterative_coupling(
            self._command_line_config, self._data
        )
        return self

    def with_execution_mode_default(self):
        """
        Set execution mode with sensible default.

        Sets the 'execution_mode' to 'run' if not already set.

        Returns
        -------
        self
            For method chaining.
        """
        execution_mode = self._data.get("general", {}).get("execution_mode", "run")
        self._data["general"]["execution_mode"] = execution_mode
        return self

    def expand_from_esm_tools_configs(self):
        """
        Expand configuration with all ESM-Tools config files.

        Loads the full configuration from all involved configuration files,
        instantiating esm_parser.ConfigSetup and merging all sources.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.get_total_config_from_user_config(
            self._data
        )
        return self

    def with_runscript_defaults(self):
        """
        Add ESM-Tools defaults to the configuration.

        Merges defaults from configs/esm_software/esm_runscripts/defaults.yaml
        into the configuration where values don't already exist.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.add_esm_runscripts_defaults_to_config(
            self._data
        )
        return self

    def validate_account(self):
        """
        Validate that required account information is present.

        Checks whether the user has defined a job scheduling account if the
        machine requires it, raising an error if missing.

        Returns
        -------
        self
            For method chaining.

        Raises
        ------
        esm_tools.user_error.UserError
            If the system requires an account but none was provided.
        """
        self._data = config_initialization.check_account(self._data)
        return self

    def with_inspect_info(self):
        """
        Complete configuration for inspect jobs.

        Sets up job type and other configuration for inspect-mode runs.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.complete_config_with_inspect(self._data)
        return self

    def remember_command_line(self):
        """
        Store command line configuration in the final config.

        Saves the command_line_config dictionary in config["general"]["command_line_config"]
        for later reference.

        Returns
        -------
        self
            For method chaining.
        """
        self._data = config_initialization.save_command_line_config(
            self._data, self._command_line_config
        )
        return self

    def build(self):
        """
        Finalize the configuration and return a SimulationConfig product.

        Returns
        -------
        SimulationConfig
            The final, immutable configuration object.
        """
        return SimulationConfig(self._data)


